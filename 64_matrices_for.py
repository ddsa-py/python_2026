matrix = [[1,2,3],
          [4,5,6],
          [7,8,9]]
print("Filas")
for fila in matrix:
    print(fila)
print()
print("Columnas or elementos")
for fila in matrix:
    for columna in fila:
        print(columna)
print()
print("Columna")
 
for fila in matrix:
    for columna in fila:
        print(columna, end = " ")
print("\n") 

print("Con elemento end=")

for fila in matrix:
    for columna in fila:
        print(columna, end= ' ')
    print()
        






































